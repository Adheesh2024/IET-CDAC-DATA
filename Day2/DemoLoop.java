
public class DemoLoop {

	public static void main(String[] args) {
		
		
		int i  = 100 ;
		System.out.println("int i : " + i);  // 100 
		
		byte b = (byte) i;		//explicit type casting 
		System.out.println("byte b : " + b);
		
		float f = i;  // implicit 
		System.out.println("float f  : " + f);
		
		float f1 = 125;
		System.out.println(f1);
		

	}

}
